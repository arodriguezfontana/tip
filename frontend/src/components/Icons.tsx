export function SectorIcon({ sector, className = 'w-4 h-4' }: { sector: string; className?: string }) {
  switch (sector?.toLowerCase()) {
    case 'pizzeria':
      return <PizzaIcon className={className} />;
    case 'cocina':
      return <KitchenIcon className={className} />;
    case 'barra':
      return <BarIcon className={className} />;
    default:
      return <UtensilsIcon className={className} />;
  }
}

export function PaymentMethodIcon({
  method,
  className = 'w-4 h-4',
}: {
  method: string | null | undefined;
  className?: string;
}) {
  switch (method?.toLowerCase()) {
    case 'efectivo':
      return <CashIcon className={className} />;
    case 'transferencia':
      return <BankIcon className={className} />;
    case 'mercadopago':
    case 'tarjeta':
      return <CreditCardIcon className={className} />;
    default:
      return <CreditCardIcon className={className} />;
  }
}

